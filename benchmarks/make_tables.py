"""Turn the benchmark CSVs into the Markdown tables embedded in the README.

Every table in the README is generated by this script, so the published numbers cannot drift
away from the CSVs they came from.
"""

from __future__ import annotations

import csv
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

RESULTS = Path(__file__).resolve().parent / "results"

MAIN_COLUMNS = ["nn", "greedy+2opt", "aco-baseline", "pso-baseline", "pso", "aco"]
HEADLINE = ["aco", "pso"]


def _load(path: Path) -> list[dict]:
    with path.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    for row in rows:
        row["n"] = int(row["n"])
        row["length"] = int(row["length"])
        row["seed"] = int(row["seed"])
        row["iterations"] = int(row["iterations"])
        row["time_to_best"] = float(row["time_to_best"])
    return rows


def _bounds() -> dict[str, dict]:
    path = RESULTS / "bounds.json"
    return json.loads(path.read_text()) if path.exists() else {}


def _reference(name: str, bounds: dict) -> tuple[int | None, str]:
    entry = bounds.get(name, {})
    if entry.get("published_optimum"):
        return entry["published_optimum"], "optimum"
    if entry.get("bound"):
        return entry["bound"], "exact" if entry.get("exact") else "bound"
    return None, ""


def _group(rows: list[dict]) -> dict[tuple[str, str], list[dict]]:
    grouped: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for row in rows:
        grouped[(row["instance"], row["algorithm"])].append(row)
    return grouped


def _gap(length: float, reference: int | None) -> str:
    if not reference:
        return "n/a"
    return f"{100.0 * (length - reference) / reference:.2f}"


def _render(headers: list[str], rows: list[list[str]], align: str = "r") -> str:
    widths = [max(len(str(cell)) for cell in [headers[i]] + [r[i] for r in rows]) for i in range(len(headers))]
    separator = ["-" * widths[0]] + [("-" * (w - 1)) + ":" for w in widths[1:]]
    lines = [
        "| " + " | ".join(h.ljust(widths[i]) for i, h in enumerate(headers)) + " |",
        "| " + " | ".join(separator[i].ljust(widths[i]) for i in range(len(headers))) + " |",
    ]
    for row in rows:
        cells = [str(row[0]).ljust(widths[0])] + [str(row[i]).rjust(widths[i]) for i in range(1, len(headers))]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def headline_table(rows: list[dict], bounds: dict) -> str:
    grouped = _group(rows)
    instances = sorted({(row["n"], row["instance"]) for row in rows})

    headers = [
        "instance",
        "n",
        "reference",
        "ACO best",
        "ACO gap %",
        "PSO best",
        "PSO gap %",
        "status",
    ]
    body = []
    for n, name in instances:
        reference, kind = _reference(name, bounds)
        label = "n/a" if reference is None else f"{reference}{'' if kind == 'optimum' else ' *'}"
        line = [name, n, label]
        found = []
        for algorithm in HEADLINE:
            runs = grouped.get((name, algorithm), [])
            if not runs:
                line += ["n/a", "n/a"]
                continue
            best = min(run["length"] for run in runs)
            found.append(best)
            line += [best, _gap(best, reference)]
        line.append(_status(min(found) if found else None, reference, kind))
        body.append(line)
    return _render(headers, body)


def _status(best: int | None, reference: int | None, kind: str) -> str:
    """A tour whose length equals a valid lower bound is optimal, and the pair is the proof.

    This is why the bound is worth computing on instances that already have a published
    optimum too: the same argument closes instances that have neither.
    """
    if best is None or reference is None:
        return ""
    if best > reference:
        return ""
    return "optimal" if kind == "optimum" else "optimal (certified here)"


def certified_optimal(rows: list[dict], bounds: dict) -> tuple[int, int, int, int]:
    """Counts of instances closed, split by whether an optimum was already published."""
    grouped = _group(rows)
    closed_known = closed_unknown = total_known = total_unknown = 0

    for name in {row["instance"] for row in rows}:
        reference, kind = _reference(name, bounds)
        if reference is None:
            continue
        best = min(
            (run["length"] for algorithm in HEADLINE for run in grouped.get((name, algorithm), [])),
            default=None,
        )
        if kind == "optimum":
            total_known += 1
            closed_known += best is not None and best <= reference
        else:
            total_unknown += 1
            closed_unknown += best is not None and best <= reference
    return closed_known, total_known, closed_unknown, total_unknown


def distribution_table(rows: list[dict], bounds: dict) -> str:
    grouped = _group(rows)
    instances = sorted({(row["n"], row["instance"]) for row in rows})

    headers = ["instance", "n", "algorithm", "best", "mean", "sd", "mean gap %", "s to best"]
    body = []
    for n, name in instances:
        reference, _ = _reference(name, bounds)
        for algorithm in HEADLINE:
            runs = grouped.get((name, algorithm), [])
            if not runs:
                continue
            lengths = [run["length"] for run in runs]
            body.append(
                [
                    name,
                    n,
                    algorithm,
                    min(lengths),
                    f"{statistics.mean(lengths):.1f}",
                    f"{statistics.pstdev(lengths):.1f}" if len(lengths) > 1 else "0.0",
                    _gap(statistics.mean(lengths), reference),
                    f"{statistics.mean(run['time_to_best'] for run in runs):.1f}",
                ]
            )
    return _render(headers, body)


def comparison_table(rows: list[dict], bounds: dict) -> str:
    """Mean gap for every configuration, which is where the baselines earn their place."""
    grouped = _group(rows)
    instances = sorted({(row["n"], row["instance"]) for row in rows})

    headers = ["instance", "n"] + MAIN_COLUMNS
    body = []
    for n, name in instances:
        reference, _ = _reference(name, bounds)
        line = [name, n]
        for algorithm in MAIN_COLUMNS:
            runs = grouped.get((name, algorithm), [])
            line.append(_gap(statistics.mean(run["length"] for run in runs), reference) if runs else "n/a")
        body.append(line)

    averages = ["mean", ""]
    for algorithm in MAIN_COLUMNS:
        gaps = []
        for n, name in instances:
            reference, _ = _reference(name, bounds)
            runs = grouped.get((name, algorithm), [])
            if runs and reference:
                gaps.append(100.0 * (statistics.mean(run["length"] for run in runs) - reference) / reference)
        averages.append(f"{statistics.mean(gaps):.2f}" if gaps else "n/a")
    body.append(averages)
    return _render(headers, body)


def _instance_gap(grouped, name: str, algorithm: str, reference: int | None) -> float | None:
    runs = grouped.get((name, algorithm), [])
    if not runs or not reference:
        return None
    return 100.0 * (statistics.mean(run["length"] for run in runs) - reference) / reference


def ablation_table(rows: list[dict], bounds: dict) -> str:
    """Per-instance mean gap for every configuration.

    A single averaged column would be misleading here: removing local search from PSO costs
    four orders of magnitude on one instance and almost nothing on another, and an average
    over that hides exactly the thing worth reporting.
    """
    grouped = _group(rows)
    instances = sorted({(row["n"], row["instance"]) for row in rows})
    configurations = sorted({row["algorithm"] for row in rows})

    headers = ["configuration"] + [name for _, name in instances] + ["median"]
    body = []
    for family in ("aco", "pso"):
        for algorithm in [family] + sorted(c for c in configurations if c.startswith(family + " -")):
            line = [algorithm]
            gaps = []
            for n, name in instances:
                reference, _ = _reference(name, bounds)
                gap = _instance_gap(grouped, name, algorithm, reference)
                line.append("n/a" if gap is None else f"{gap:.2f}")
                if gap is not None:
                    gaps.append(gap)
            line.append(f"{statistics.median(gaps):.2f}" if gaps else "n/a")
            body.append(line)
    return _render(headers, body)


def ablation_cost_table(rows: list[dict], bounds: dict) -> str:
    """What each mechanism is worth, as the median gap increase when it is removed."""
    grouped = _group(rows)
    instances = sorted({(row["n"], row["instance"]) for row in rows})
    configurations = sorted({row["algorithm"] for row in rows})

    def deltas(family: str, algorithm: str) -> list[float]:
        values = []
        for n, name in instances:
            reference, _ = _reference(name, bounds)
            full = _instance_gap(grouped, name, family, reference)
            without = _instance_gap(grouped, name, algorithm, reference)
            if full is not None and without is not None:
                values.append(without - full)
        return values

    body = []
    for family in ("aco", "pso"):
        for algorithm in sorted(c for c in configurations if c.startswith(family + " -")):
            values = deltas(family, algorithm)
            if not values:
                continue
            median = statistics.median(values)
            body.append(
                [
                    algorithm.split(" -", 1)[1],
                    family,
                    f"{median:+.2f}",
                    f"{min(values):+.2f}",
                    f"{max(values):+.2f}",
                ]
            )
    return _render(
        ["mechanism", "algorithm", "median cost of removal", "best case", "worst case"], body
    )


def stagnation_table(rows: list[dict], bounds: dict) -> str:
    """Stagnation recovery on and off at a long budget, where the colony has time to converge."""
    grouped = _group(rows)
    instances = sorted({(row["n"], row["instance"]) for row in rows})

    headers = [
        "instance",
        "n",
        "iterations",
        "with recovery",
        "without",
        "gap % with",
        "gap % without",
    ]
    body = []
    for n, name in instances:
        reference, _ = _reference(name, bounds)
        with_runs = grouped.get((name, "aco"), [])
        without_runs = grouped.get((name, "aco -stagnation"), [])
        if not with_runs or not without_runs:
            continue
        with_mean = statistics.mean(run["length"] for run in with_runs)
        without_mean = statistics.mean(run["length"] for run in without_runs)
        body.append([
            name,
            n,
            f"{statistics.mean(run['iterations'] for run in with_runs):.0f}",
            f"{with_mean:.1f}",
            f"{without_mean:.1f}",
            _gap(with_mean, reference),
            _gap(without_mean, reference),
        ])
    return _render(headers, body)


def bounds_table(bounds: dict) -> str:
    headers = ["instance", "n", "lower bound", "published optimum", "status"]
    body = []
    for name, entry in sorted(bounds.items(), key=lambda item: (item[1]["n"], item[0])):
        optimum = entry.get("published_optimum")
        if entry.get("exact"):
            status = "proven optimal"
        elif optimum:
            status = f"{100.0 * entry['bound'] / optimum:.2f} % of optimum"
        else:
            status = "lower bound"
        body.append([name, entry["n"], entry["bound"], optimum or "unknown", status])
    return _render(headers, body)


def main() -> int:
    bounds = _bounds()
    output = RESULTS / "tables.md"
    sections = []

    if (RESULTS / "results.csv").exists():
        rows = _load(RESULTS / "results.csv")
        sections.append("## Headline results\n\n" + headline_table(rows, bounds))
        sections.append("## Distribution over seeds\n\n" + distribution_table(rows, bounds))
        sections.append("## All configurations, mean gap\n\n" + comparison_table(rows, bounds))

    if (RESULTS / "ablation.csv").exists():
        rows = _load(RESULTS / "ablation.csv")
        sections.append("## Ablation\n\n" + ablation_table(rows, bounds))
        sections.append(
            "## Cost of removing each mechanism\n\n" + ablation_cost_table(rows, bounds)
        )

    if (RESULTS / "stagnation.csv").exists():
        rows = _load(RESULTS / "stagnation.csv")
        sections.append(
            "## Stagnation recovery at a long budget\n\n" + stagnation_table(rows, bounds)
        )

    if bounds:
        sections.append("## Lower bounds\n\n" + bounds_table(bounds))

    text = "\n\n".join(sections) + "\n"
    output.write_text(text)
    print(text)
    print(f"written to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
